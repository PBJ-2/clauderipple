// `clauderipple app --install|--uninstall`: something to double-click that opens the menu-bar app.
//
// Installed from npm there is no application to open, and the menu-bar app is exactly what a
// person needs when the router is down (it offers repair and Claude's default connection). So a
// launcher runs `clauderipple tray --ensure`: fetch Electron once if it is missing, then start the
// tray the way `clauderipple tray` does.
//
//   macOS   ~/Applications/ClaudeRipple.app — Info.plist + a shell script, bundle id
//           com.clauderipple.launcher (the router's own background bundle in ~/.clauderipple is
//           com.clauderipple.router, the packaged app com.clauderipple.app; none collide)
//   Windows Start Menu and Desktop shortcuts (.lnk, WScript.Shell) to a hidden PowerShell launcher
//   Linux   ~/.local/share/applications/clauderipple.desktop
//
// CLAUDERIPPLE_LAUNCHER_DIR replaces every target directory (tests, or a custom location).

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { withFileLock } from "../../router/src/locked-file.ts";
import type { Runtime } from "./runtime.ts";
import { windowsPowerShellEnv } from "./windows-powershell.ts";
import { normalizeHome, ownerOf, type Ownership } from "./ownership.ts";

export const LAUNCHER_BUNDLE_ID = "com.clauderipple.launcher";
const APP_NAME = "ClaudeRipple";
const DESKTOP_MARK = "X-ClaudeRipple-Launcher=1";

export type LauncherResult = { ok: boolean; paths: string[]; detail: string };

type Opts = { rt: Runtime; home: string; version: string; platform?: NodeJS.Platform; powershell?: (script: string) => string };

function overrideDir(): string | null {
  return process.env.CLAUDERIPPLE_LAUNCHER_DIR ?? null;
}

export function macAppPath(): string {
  return path.join(overrideDir() ?? path.join(os.homedir(), "Applications"), `${APP_NAME}.app`);
}

export function desktopEntryPath(): string {
  const data = process.env.XDG_DATA_HOME || path.join(os.homedir(), ".local", "share");
  return path.join(overrideDir() ?? path.join(data, "applications"), "clauderipple.desktop");
}

export function windowsTrayLauncherPath(home: string): string {
  return path.join(home, "clauderipple-tray.ps1");
}

/** POSIX single-quoted literal. */
function sh(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** PowerShell single-quoted literal; the only escape inside one is a doubled quote. */
function ps(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** A desktop-entry Exec argument (freedesktop Desktop Entry spec, "The Exec key"). */
function execArg(value: string): string {
  return `"${value.replace(/([\\"`$])/g, "\\$1").replace(/%/g, "%%")}"`;
}

const OWNER_MARK = "ClaudeRipple-Launcher-Home=";

function ownerMarker(home: string): string {
  return OWNER_MARK + Buffer.from(normalizeHome(home), "utf8").toString("base64");
}

function launchEnv(rt: Runtime, home: string): Record<string, string> {
  return { ...rt.env, CLAUDERIPPLE_HOME: home };
}

/** The app icon (icon.icns / icon.png / icon.ico), committed in the app's assets and shipped in the npm package beside the tray. */
export function findIcon(rt: Pick<Runtime, "repo">, file: string): string | null {
  for (const dir of [path.join(rt.repo, "packages", "app", "assets"), path.join(rt.repo, "dist", "app", "assets")]) {
    const p = path.join(dir, file);
    if (fs.existsSync(p)) return p;
  }
  return null;
}

export function macInfoPlist(version: string, icon: boolean): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${APP_NAME}</string>
  <key>CFBundleDisplayName</key><string>${APP_NAME}</string>
  <key>CFBundleIdentifier</key><string>${LAUNCHER_BUNDLE_ID}</string>
  <key>CFBundleVersion</key><string>${version}</string>
  <key>CFBundleShortVersionString</key><string>${version}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>${APP_NAME}</string>
${icon ? "  <key>CFBundleIconFile</key><string>icon</string>\n" : ""}  <key>LSUIElement</key><true/>
</dict>
</plist>
`;
}

export function macLauncherScript(rt: Runtime, home: string): string {
  const log = path.join(home, "logs", "launcher.log");
  return [
    "#!/bin/sh",
    "# Opens the ClaudeRipple menu-bar app (generated by `clauderipple app --install`).",
    `# ${ownerMarker(home)}`,
    ...Object.entries(launchEnv(rt, home)).map(([k, v]) => `export ${k}=${sh(v)}`),
    `mkdir -p ${sh(path.dirname(log))}`,
    `exec ${sh(rt.node)} ${sh(rt.cli)} tray --ensure >> ${sh(log)} 2>&1`,
    "",
  ].join("\n");
}

export function desktopEntry(rt: Runtime, home: string): string {
  const env = Object.entries(launchEnv(rt, home)).map(([k, v]) => execArg(`${k}=${v}`));
  const icon = findIcon(rt, "icon.png");
  return [
    "[Desktop Entry]",
    "Type=Application",
    `Name=${APP_NAME}`,
    "Comment=ClaudeRipple menu-bar app: router status, repair, and Claude's default connection",
    `Exec=env ${env.join(" ")} ${execArg(rt.node)} ${execArg(rt.cli)} tray --ensure`,
    ...(icon ? [`Icon=${icon}`] : []),
    "Terminal=false",
    "Categories=Utility;Development;",
    DESKTOP_MARK,
    `X-${ownerMarker(home)}`,
    "",
  ].join("\n");
}

export function windowsTrayLauncher(rt: Runtime, home: string): string {
  // Its own log, not logs\launcher.log: the router's launcher holds that file open for as long as
  // the router runs (schtasks.ts's Start-Process -RedirectStandardOutput), and a second writer
  // failed to open it and died before node started — the shortcut did nothing, with no window to
  // say why (#87). The tray can do without a log, so if this one cannot be opened either the
  // command runs again without it. Windows PowerShell runs the command only after the redirection
  // has opened its file (measured in the Windows 11 VM, 2026-10-24), so the fallback never runs
  // the command twice.
  const log = path.join(home, "logs", "tray-launcher.log");
  const command = `& ${ps(rt.node)} ${ps(rt.cli)} tray --ensure`;
  // -File is read by Windows PowerShell 5.1, which needs a BOM to recognise UTF-8.
  return String.fromCharCode(0xFEFF) + [
    `# ${ownerMarker(home)}`,
    ...Object.entries(launchEnv(rt, home)).map(([k, v]) => `$env:${k} = ${ps(v)}`),
    `New-Item -ItemType Directory -Force -Path ${ps(path.dirname(log))} | Out-Null`,
    `try { ${command} *>> ${ps(log)} } catch { ${command} }`,
  ].join("\r\n") + "\r\n";
}

/**
 * Creates (or, with `remove`, deletes) the shortcuts and prints each path. Without an override the
 * folders are the user's own Start Menu programs and Desktop, as Windows names them.
 */
type Shortcut = { path: string; exists: boolean; target: string; args: string; description: string };

export function windowsShortcutScript(launcher: string, iconSource: string, dir: string | null, remove = false, expected?: Shortcut[]): string {
  const targets = dir
    ? `@(${ps(path.join(dir, "Start Menu", `${APP_NAME}.lnk`))}, ${ps(path.join(dir, "Desktop", `${APP_NAME}.lnk`))})`
    : `@((Join-Path ([Environment]::GetFolderPath('Programs')) '${APP_NAME}.lnk'), (Join-Path ([Environment]::GetFolderPath('Desktop')) '${APP_NAME}.lnk'))`;
  // Inspect every shortcut before changing any of them. Get-Item distinguishes missing entries
  // from access/COM failures; reparse points are not shortcuts we may replace.
  const inspect = [
    `$ErrorActionPreference = 'Stop'`,
    `[Console]::OutputEncoding = [System.Text.UTF8Encoding]::new($false)`,
    `$ws = New-Object -ComObject WScript.Shell`,
    `$rows = @(foreach ($p in ${targets}) { $item = $null; try { $item = Get-Item -LiteralPath $p -ErrorAction Stop } catch { if ($_.FullyQualifiedErrorId -ne 'PathNotFound,Microsoft.PowerShell.Commands.GetItemCommand') { throw } }; if ($null -eq $item) { [pscustomobject]@{path=$p;exists=$false;target='';args='';description=''} } else { if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Shortcut is a reparse point; left alone' }; $s = $ws.CreateShortcut($p); [pscustomobject]@{path=$p;exists=$true;target=$s.TargetPath;args=$s.Arguments;description=$s.Description} } })`,
  ];
  if (!expected) return [...inspect, `ConvertTo-Json -InputObject @($rows) -Compress`].join("; ");
  const guard = `$expected = ConvertFrom-Json ${ps(JSON.stringify(expected))}; if ($rows.Count -ne $expected.Count) { throw 'Shortcuts changed; left alone' }; for ($i=0; $i -lt $rows.Count; $i++) { foreach ($key in @('path','exists','target','args','description')) { if ($rows[$i].$key -cne $expected[$i].$key) { throw 'Shortcuts changed; left alone' } } }`;
  if (remove) return [...inspect, guard, `foreach ($r in $rows) { if ($r.exists) { Remove-Item -LiteralPath $r.path -Force; $r.path } }`].join("; ");
  // conhost --headless avoids opening a console window (#49).
  const args = shortcutArguments(launcher);
  return [...inspect, guard,
    `foreach ($p in ${targets}) { New-Item -ItemType Directory -Force -Path (Split-Path -Parent $p) | Out-Null; $s = $ws.CreateShortcut($p); $s.TargetPath = (Join-Path $env:SystemRoot 'System32\\conhost.exe'); $s.Arguments = ${ps(args)}; $s.IconLocation = ${ps(`${iconSource},0`)}; $s.Description = ${ps(ownerMarker(launcher.replace(/[\\/]clauderipple-tray\.ps1$/, "")))}; $s.Save(); $p }`,
  ].join("; ");
}

function runPowerShell(script: string): string {
  return execFileSync("powershell.exe", ["-NoProfile", "-NonInteractive", "-Command", script], {
    env: windowsPowerShellEnv(),
    stdio: ["ignore", "pipe", "pipe"],
    windowsHide: true,
    timeout: 30_000,
  }).toString();
}

/** Bundle id of an existing .app, or null when it has none we can read. */
export function bundleIdOf(app: string): string | null {
  try {
    const plist = fs.readFileSync(path.join(app, "Contents", "Info.plist"), "utf8");
    return /<key>CFBundleIdentifier<\/key>\s*<string>([^<]*)<\/string>/.exec(plist)?.[1] ?? null;
  } catch {
    return null;
  }
}

function shortcutArguments(launcher: string): string {
  return `--headless powershell.exe -NoProfile -NonInteractive -WindowStyle Hidden -ExecutionPolicy Bypass -File "${launcher}"`;
}

function recordedOwner(text: string, home: string): Ownership | null {
  const records = text.replace(/^﻿/, "").split(/\r?\n/).filter(line => line.includes(OWNER_MARK));
  if (!records.length) return null;
  const value = /^(?:# |X-)?ClaudeRipple-Launcher-Home=([A-Za-z0-9+/]+=*)$/.exec(records[0]!)?.[1];
  if (records.length !== 1 || !value) return ownerOf(null, home);
  const decoded = Buffer.from(value, "base64").toString("utf8");
  if (Buffer.from(decoded).toString("base64") !== value || (!path.isAbsolute(decoded) && !/^[A-Za-z]:[\\/]/.test(decoded))) return ownerOf(null, home);
  return ownerOf(decoded, home);
}

function withoutOwner(text: string): string {
  return text.replace(/^﻿/, "").split(/\r?\n/).filter(line => !line.includes(OWNER_MARK)).join("\n");
}

/**
 * The home an installed launcher records, in the form each platform's generated script uses:
 * `export CLAUDERIPPLE_HOME='…'` (macOS), the desktop entry's `Exec=env "CLAUDERIPPLE_HOME=…"`
 * (Linux) and `$env:CLAUDERIPPLE_HOME = '…'` (Windows). This is the same evidence a service
 * definition carries, and the version before the installed-for marker recorded no more than this.
 */
export function recordedLaunchHome(text: string, platform: "darwin" | "linux" | "win32"): string | null {
  const body = text.replace(/^﻿/, "");
  const values: string[] = [];
  if (platform === "darwin") {
    for (const match of body.matchAll(/^export CLAUDERIPPLE_HOME='((?:[^']|'\\'')*)'$/gm)) values.push(match[1]!.replace(/'\\''/g, "'"));
  } else if (platform === "linux") {
    for (const match of body.matchAll(/"CLAUDERIPPLE_HOME=((?:[^"\\]|\\.)*)"/g)) values.push(match[1]!.replace(/\\(.)/g, "$1").replace(/%%/g, "%"));
  } else {
    for (const match of body.matchAll(/^\$env:CLAUDERIPPLE_HOME = '((?:[^']|'')*)'$/gm)) values.push(match[1]!.replace(/''/g, "'"));
  }
  // Two different records make the file ambiguous; no record says nothing.
  return values.length === 1 && values[0] ? values[0] : null;
}

/** Missing is not the same as unreadable. Never follow launcher symlinks for writes. */
function fileOwner(file: string, opts: Opts, platform: "darwin" | "linux" | "win32"): Ownership {
  try {
    const stat = fs.lstatSync(file);
    if (stat.isSymbolicLink()) return ownerOf(null, opts.home);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { state: "absent", home: null };
    throw error;
  }
  let source = file;
  if (platform === "darwin") {
    const plist = fs.readFileSync(path.join(file, "Contents", "Info.plist"), "utf8");
    if (!plist.includes(`<key>CFBundleIdentifier</key><string>${LAUNCHER_BUNDLE_ID}</string>`)) return ownerOf(null, opts.home);
    source = path.join(file, "Contents", "MacOS", APP_NAME);
    // Intermediate bundle links would otherwise redirect writes outside the checked bundle.
    for (const part of ["Contents", "Contents/MacOS", `Contents/MacOS/${APP_NAME}`, "Contents/Info.plist", "Contents/Resources", "Contents/Resources/icon.icns"]) {
      try {
        if (fs.lstatSync(path.join(file, part)).isSymbolicLink()) return ownerOf(null, opts.home);
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      }
    }
  }
  const text = fs.readFileSync(source, "utf8");
  const marker = recordedOwner(text, opts.home);
  if (marker) return marker;
  const rendered = platform === "darwin" ? macLauncherScript(opts.rt, opts.home) : platform === "linux" ? desktopEntry(opts.rt, opts.home) : windowsTrayLauncher(opts.rt, opts.home);
  // A script this version would render byte for byte is ours even with no marker (an older
  // version's script, moved home excepted by the comparison itself).
  if (withoutOwner(text) === withoutOwner(rendered)) return ownerOf(opts.home, opts.home);
  // Otherwise the recorded home is the evidence: a launcher another installation wrote names its
  // own home, and a runtime path that moved with an update does not change which home it is for (B22).
  return ownerOf(recordedLaunchHome(text, platform), opts.home);
}

function refused(ownership: Ownership): LauncherResult | null {
  if (ownership.state === "ours" || ownership.state === "absent") return null;
  return { ok: false, paths: [], detail: ownership.state === "other" ? "Launcher belongs to another installation; left it alone." : "Launcher ownership is unknown; left it alone." };
}

/** Pure ownership boundary for the WScript.Shell inspection response. */
export function windowsShortcutOwner(row: Pick<Shortcut, "exists" | "target" | "args" | "description">, home: string): Ownership {
  if (!row.exists) return { state: "absent", home: null };
  const match = /^--headless powershell\.exe -NoProfile -NonInteractive -WindowStyle Hidden -ExecutionPolicy Bypass -File "([^"\r\n]+)[\\/]clauderipple-tray\.ps1"$/.exec(row.args);
  if (!match || !/^[A-Za-z]:[\\/].*[\\/]System32[\\/]conhost\.exe$/i.test(row.target)) return ownerOf(null, home);
  const targetOwner = ownerOf(match[1]!, home);
  if (targetOwner.state !== "ours") return targetOwner;
  return recordedOwner(row.description, home) ?? (row.description === "ClaudeRipple menu-bar app" ? targetOwner : ownerOf(null, home));
}

function isShortcut(row: unknown): row is Shortcut {
  return !!row && typeof row === "object" && "path" in row && typeof row.path === "string" && "exists" in row && typeof row.exists === "boolean" && "target" in row && typeof row.target === "string" && "args" in row && typeof row.args === "string" && "description" in row && typeof row.description === "string";
}

function windowsOperation(opts: Opts, remove: boolean): LauncherResult {
  const launcher = windowsTrayLauncherPath(opts.home);
  const localOwner = fileOwner(launcher, opts, "win32");
  const local = refused(localOwner);
  if (local) return local;
  const run = opts.powershell ?? runPowerShell;
  const icon = findIcon(opts.rt, "icon.ico") ?? opts.rt.node;
  const rows: unknown = JSON.parse(run(windowsShortcutScript(launcher, icon, overrideDir())));
  if (!Array.isArray(rows) || rows.length !== 2) throw new Error("Invalid shortcut inspection result");
  const shortcuts: Shortcut[] = [];
  for (const row of rows) {
    if (!isShortcut(row)) throw new Error("Invalid shortcut inspection record");
    shortcuts.push(row);
    const denied = refused(windowsShortcutOwner(row, opts.home));
    if (denied) return denied;
  }
  const out = run(windowsShortcutScript(launcher, icon, overrideDir(), remove, shortcuts));
  if (remove) {
    try { fs.unlinkSync(launcher); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  } else {
    fs.mkdirSync(opts.home, { recursive: true });
    fs.writeFileSync(launcher, windowsTrayLauncher(opts.rt, opts.home));
  }
  const paths = out.split(/\r?\n/).map(line => line.trim()).filter(Boolean);
  if (remove && localOwner.state === "ours") paths.push(launcher);
  return { ok: true, paths, detail: remove ? (paths.length ? "launcher removed" : "no launcher was installed") : `${APP_NAME} is in the Start Menu and on the Desktop.` };
}

function install(opts: Opts): LauncherResult {
  const platform = opts.platform ?? process.platform;
  if (opts.rt.packaged) return { ok: true, paths: [], detail: "This is the standalone ClaudeRipple app, which opens the menu-bar app itself; no launcher needed." };
  if (platform === "darwin") {
    const app = macAppPath();
    const denied = refused(fileOwner(app, opts, "darwin"));
    if (denied) return denied;
    const contents = path.join(app, "Contents");
    fs.mkdirSync(path.join(contents, "MacOS"), { recursive: true });
    const icns = findIcon(opts.rt, "icon.icns");
    if (icns) {
      fs.mkdirSync(path.join(contents, "Resources"), { recursive: true });
      fs.copyFileSync(icns, path.join(contents, "Resources", "icon.icns"));
    }
    fs.writeFileSync(path.join(contents, "Info.plist"), macInfoPlist(opts.version, icns !== null));
    fs.writeFileSync(path.join(contents, "MacOS", APP_NAME), macLauncherScript(opts.rt, opts.home), { mode: 0o755 });
    fs.chmodSync(path.join(contents, "MacOS", APP_NAME), 0o755);
    return { ok: true, paths: [app], detail: `Open ${APP_NAME} from ${path.dirname(app)} (or Spotlight) to start the menu-bar app.` };
  }
  if (platform === "linux") {
    const file = desktopEntryPath();
    const denied = refused(fileOwner(file, opts, "linux"));
    if (denied) return denied;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, desktopEntry(opts.rt, opts.home), { mode: 0o755 });
    return { ok: true, paths: [file], detail: `${APP_NAME} is in your applications menu.` };
  }
  if (platform === "win32") {
    return windowsOperation(opts, false);
  }
  return { ok: false, paths: [], detail: `no launcher for ${platform}; start the menu-bar app with: clauderipple tray` };
}

function uninstall(opts: Opts): LauncherResult {
  const platform = opts.platform ?? process.platform;
  const removed: string[] = [];
  if (platform === "darwin") {
    const app = macAppPath();
    const ownership = fileOwner(app, opts, "darwin");
    const denied = refused(ownership);
    if (denied) return denied;
    if (ownership.state === "ours") {
      fs.rmSync(app, { recursive: true, force: true });
      removed.push(app);
    }
  } else if (platform === "linux") {
    const file = desktopEntryPath();
    const ownership = fileOwner(file, opts, "linux");
    const denied = refused(ownership);
    if (denied) return denied;
    if (ownership.state === "ours") {
      fs.rmSync(file);
      removed.push(file);
    }
  } else if (platform === "win32") {
    return windowsOperation(opts, true);
  }
  return { ok: true, paths: removed, detail: removed.length ? "launcher removed" : "no launcher was installed" };
}

/** The shared artifact to lock on: every installation on the account writes the same one. */
function launcherLockPath(platform: NodeJS.Platform): string {
  if (platform === "darwin") return macAppPath();
  if (platform === "linux") return desktopEntryPath();
  const dir = overrideDir();
  return dir ? path.join(dir, `ClaudeRipple.lnk`) : path.join(os.homedir(), ".clauderipple-launcher");
}

function launcherOperation(opts: Opts, operation: (opts: Opts) => LauncherResult): LauncherResult {
  try {
    // Inspect-then-write is one step: two installations installing or removing at once must not
    // both pass the ownership check and then write over each other (2026-10-25 lock audit).
    return withFileLock(launcherLockPath(opts.platform ?? process.platform), () => operation(opts));
  } catch (error) {
    return { ok: false, paths: [], detail: `Launcher operation failed: ${error instanceof Error ? error.message : String(error)}` };
  }
}

export function installLauncher(opts: Opts): LauncherResult {
  return launcherOperation(opts, install);
}

export function uninstallLauncher(opts: Opts): LauncherResult {
  return launcherOperation(opts, uninstall);
}
