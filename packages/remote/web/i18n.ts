export const dictionaries: Record<Lang, Record<Key, string>> = { ko, en };

let current: Lang = "ko";

export function pickLang(navLangs: readonly string[], stored: string | null): Lang {
  if (stored === "ko" || stored === "en") return stored;
  for (const l of navLangs) {
    if (l.toLowerCase().startsWith("ko")) return "ko";
    if (l.toLowerCase().startsWith("en")) return "en";
  }
  return "ko";
}

export function setLang(lang: Lang): void { current = lang; }
export function lang(): Lang { return current; }

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = dictionaries[current][key] ?? key;
  // `{host}` is the connected computer's name. Every call site that has a HostInfo passes it;
  // the rest get the neutral fallback so no copy ever hardcodes a platform.
  if (s.includes("{host}")) s = s.replaceAll("{host}", String(vars?.host ?? dictionaries[current]["host.fallback"]));
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  // `{n|tool|tools}` picks the singular when that count is 1 (English needs it; Korean never uses it).
  return s.replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, k: string, one: string, other: string) => (Number(vars?.[k]) === 1 ? one : other));
}
