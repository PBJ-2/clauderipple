test("a lost manifest adopts only marked current targets, not renamed copies or hand files", () => {
  const dir = tmp();
  const manifest = path.join(dir, "generated-agents.json");
  const cfg = cfgWith({ p: p(["model-a", "model-b"]) });
  const target = path.join(dir, "model-a.md");
  const copy = path.join(dir, "my-copy.md");
  const handFile = path.join(dir, "model-b.md");

  syncAgentFiles(cfg, dir, undefined, { manifestPath: manifest });
  const expected = fs.readFileSync(target, "utf8");
  const copied = expected.replace("name: model-a\n", "name: my-copy\n");
  const hand = "---\nname: model-b\nmodel: personal-model\n---\n" +
    "# Generated by ClaudeRipple from config.json — edits are overwritten; to customise, copy to another name.\n" +
    "Generated by ClaudeRipple from config.json — edits are overwritten\n";
  fs.writeFileSync(target, expected + "stale body\n");
  fs.writeFileSync(copy, copied);
  fs.writeFileSync(handFile, hand);
  fs.writeFileSync(manifest, JSON.stringify({ agents: [] }));

  syncAgentFiles(cfg, dir, undefined, { manifestPath: manifest });

  assert.equal(fs.readFileSync(target, "utf8"), expected, "the marked target is adopted and rewritten");
  assert.deepEqual(JSON.parse(fs.readFileSync(manifest, "utf8")).agents, ["model-a"], "only the target is owned");
  assert.equal(fs.readFileSync(copy, "utf8"), copied, "the marked non-target copy survives untouched");
  assert.equal(fs.readFileSync(handFile, "utf8"), hand, "a marker in the body does not make a hand file ours");
  assert.deepEqual(generatedAgents(cfg, dir, manifest), [{ name: "model-a", model: "model-a", provider: "p" }]);
});

