test("retouchLater moves the files' mtime after the delay and skips one removed since", async () => {
  const dir = tmp();
  const kept = path.join(dir, "kept.md");
  const gone = path.join(dir, "gone.md");
  fs.writeFileSync(kept, "x");
  fs.writeFileSync(gone, "x");
  const old = new Date(Date.now() - 3_600_000);
  fs.utimesSync(kept, old, old);

  retouchLater([gone, kept], 10);
  fs.rmSync(gone);
  // Within a second: some file systems keep mtime to a coarser step than the Date passed in.
  assert.ok(Math.abs(fs.statSync(kept).mtimeMs - old.getTime()) < 1_000, "not before the delay");
  await new Promise((resolve) => setTimeout(resolve, 60));

  assert.ok(fs.statSync(kept).mtimeMs > old.getTime() + 3_000_000, "touched");
  assert.equal(fs.readFileSync(kept, "utf8"), "x", "content untouched");
});

