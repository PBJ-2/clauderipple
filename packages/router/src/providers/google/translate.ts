// ---- Gemini stream → Anthropic stream ----------------------------------------------

export type AnthropicUsage = { input_tokens: number; output_tokens: number; cache_read_input_tokens: number; cache_creation_input_tokens: number };
export type AnthropicEvent = { event: string; data: Record<string, unknown> };

type TextOutputBlock = { type: "text"; text: string };
type ThinkingOutputBlock = { type: "thinking"; thinking: string };
type ToolOutputBlock = { type: "tool_use"; id: string; name: string; input: unknown; args: string; index: number };
type OutputBlock = TextOutputBlock | ThinkingOutputBlock | ToolOutputBlock;
type OpenBlock = { kind: "text" | "thinking" | "tool"; index: number; toolIndex?: number };

type GeminiChunk = {
  candidates?: { content?: { parts?: GeminiPart[] }; finishReason?: unknown }[];
  usageMetadata?: { promptTokenCount?: unknown; candidatesTokenCount?: unknown; cachedContentTokenCount?: unknown; thoughtsTokenCount?: unknown };
  error?: { message?: unknown; status?: unknown; code?: unknown };
};

/** Called with each functionCall part's (Signatures) as they arrive, so the adapter can remember them. */
export type SignatureSink = (info: { id: string; name: string; signature: string | undefined }) => void;

/** Maps Gemini `streamGenerateContent` SSE chunks to Anthropic Messages SSE. */
export class GoogleStreamMapper {
  private started = false;
  private finished = false;
  private blockIndex = -1;
  private open: OpenBlock | null = null;
  private sawTool = false;
  private finishReason: string | undefined;
  private sawCompletion = false;
  private toolCounter = 0;
  private readonly toolNames: ReadonlyMap<string, string>;
  private readonly onFunctionCall: SignatureSink | undefined;
  readonly messageId = `msg_${crypto.randomBytes(12).toString("hex")}`;
  readonly content: OutputBlock[] = [];
  usage: AnthropicUsage = { input_tokens: 0, output_tokens: 0, cache_read_input_tokens: 0, cache_creation_input_tokens: 0 };
  stopReason: "end_turn" | "tool_use" | "max_tokens" = "end_turn";
  failure: { type: string; message: string } | undefined;

  readonly model: string;
  private readonly startInput: number;

  constructor(model: string, startInput = 0, toolNames: ReadonlyMap<string, string> = new Map(), onFunctionCall?: SignatureSink) {
    this.model = model;
    this.startInput = startInput;
    this.toolNames = toolNames;
    this.onFunctionCall = onFunctionCall;
  }

  get isFinished(): boolean { return this.finished; }
  /** Whether Gemini said the answer was over (a `finishReason` was seen). */
  get completed(): boolean { return this.sawCompletion; }

  start(): AnthropicEvent[] {
    if (this.started) return [];
    this.started = true;
    return [{ event: "message_start", data: { type: "message_start", message: { id: this.messageId, type: "message", role: "assistant", model: this.model, content: [], stop_reason: null, stop_sequence: null, usage: { input_tokens: this.startInput, output_tokens: 0, cache_read_input_tokens: 0, cache_creation_input_tokens: 0 } } } }];
  }

  private closeBlock(): AnthropicEvent[] {
    if (!this.open) return [];
    const index = this.open.index;
    this.open = null;
    return [{ event: "content_block_stop", data: { type: "content_block_stop", index } }];
  }

  private openBlock(kind: "text" | "thinking" | "tool", contentBlock: Record<string, unknown>, toolIndex?: number): AnthropicEvent[] {
    const out = this.closeBlock();
    const index = ++this.blockIndex;
    this.open = { kind, index, ...(toolIndex === undefined ? {} : { toolIndex }) };
    out.push({ event: "content_block_start", data: { type: "content_block_start", index, content_block: contentBlock } });
    return out;
  }

  private setUsage(value: GeminiChunk["usageMetadata"]): void {
    if (!value || typeof value !== "object") return;
    const num = (v: unknown): number => (typeof v === "number" && Number.isFinite(v) ? Math.max(0, v) : 0);
    const prompt = num(value.promptTokenCount);
    const cached = num(value.cachedContentTokenCount);
    const candidates = num(value.candidatesTokenCount);
    const thoughts = num(value.thoughtsTokenCount);
    this.usage = {
      input_tokens: Math.max(0, prompt - cached),
      output_tokens: candidates + thoughts,
      cache_read_input_tokens: cached,
      cache_creation_input_tokens: 0,
    };
  }

  /** The vendor echoes the name it was given; Claude Code only recognises the original. */
  private restore(name: string): string {
    return this.toolNames.get(name) ?? name;
  }

  private feedParts(parts: readonly GeminiPart[]): AnthropicEvent[] {
    const out: AnthropicEvent[] = [];
    for (const part of parts) {
      if (typeof part.text === "string" && part.text) {
        if (part.thought === true) {
          if (!this.open || this.open.kind !== "thinking") {
            this.content.push({ type: "thinking", thinking: "" });
            out.push(...this.openBlock("thinking", { type: "thinking", thinking: "" }));
          }
          const last = this.content[this.content.length - 1];
          if (last?.type === "thinking") last.thinking += part.text;
          out.push({ event: "content_block_delta", data: { type: "content_block_delta", index: this.open!.index, delta: { type: "thinking_delta", thinking: part.text } } });
        } else {
          if (!this.open || this.open.kind !== "text") {
            this.content.push({ type: "text", text: "" });
            out.push(...this.openBlock("text", { type: "text", text: "" }));
          }
          const last = this.content[this.content.length - 1];
          if (last?.type === "text") last.text += part.text;
          out.push({ event: "content_block_delta", data: { type: "content_block_delta", index: this.open!.index, delta: { type: "text_delta", text: part.text } } });
        }
        continue;
      }
      if (part.functionCall && typeof part.functionCall.name === "string") {
        this.sawTool = true;
        const index = this.toolCounter++;
        const name = this.restore(part.functionCall.name);
        const id = `toolu_${crypto.randomBytes(12).toString("hex")}`;
        const args = typeof part.functionCall.args === "object" && part.functionCall.args !== null ? JSON.stringify(part.functionCall.args) : "{}";
        const tool: ToolOutputBlock = { type: "tool_use", id, name, input: {}, args, index };
        this.content.push(tool);
        // A whole functionCall arrives in one part, so it opens, takes its arguments in a single
        // delta, and closes — there is nothing to stream.
        out.push(...this.openBlock("tool", { type: "tool_use", id, name, input: {} }, index));
        out.push({ event: "content_block_delta", data: { type: "content_block_delta", index: this.open!.index, delta: { type: "input_json_delta", partial_json: args } } });
        out.push(...this.closeBlock());
        // Let the adapter remember the signature against the id it just minted, so the next turn can
        // send it back with the replayed functionCall.
        this.onFunctionCall?.({ id, name, signature: typeof part.thoughtSignature === "string" && part.thoughtSignature ? part.thoughtSignature : undefined });
      }
      // inlineData (image output) is not handled in this stage; it is ignored rather than guessed at.
    }
    // A part's own text may have been empty but a later part non-empty; the caller decides on close.
    return out;
  }

  feed(chunk: GeminiChunk): AnthropicEvent[] {
    if (this.finished) return [];
    const out = [...this.start()];
    if (chunk.error && typeof chunk.error === "object") {
      const message = typeof chunk.error.message === "string" ? chunk.error.message : "upstream error";
      const status = typeof chunk.error.status === "string" ? chunk.error.status : undefined;
      return [...out, ...this.fail(message, status)];
    }
    if (chunk.usageMetadata) this.setUsage(chunk.usageMetadata);
    const candidates = Array.isArray(chunk.candidates) ? chunk.candidates : [];
    for (const candidate of candidates) {
      if (typeof candidate?.finishReason === "string" && candidate.finishReason) {
        this.finishReason = candidate.finishReason;
        this.sawCompletion = true;
      }
      const parts = candidate?.content?.parts;
      if (Array.isArray(parts)) out.push(...this.feedParts(parts));
    }
    return out;
  }

  finish(): AnthropicEvent[] {
    if (this.finished) return [];
    this.finished = true;
    this.stopReason = this.sawTool ? "tool_use" : this.finishReason === "MAX_TOKENS" ? "max_tokens" : "end_turn";
    return [...this.start(), ...this.closeBlock(), { event: "message_delta", data: { type: "message_delta", delta: { stop_reason: this.stopReason, stop_sequence: null }, usage: this.usage } }, { event: "message_stop", data: { type: "message_stop" } }];
  }

  fail(message: string, status?: string): AnthropicEvent[] {
    if (this.finished) return [];
    this.finished = true;
    // `overloaded_error` is the one mid-stream error Claude Code retries on its own; `api_error` is
    // final. Gemini's RESOURCE_EXHAUSTED becomes a rate limit the client backs off from.
    const type = status === "RESOURCE_EXHAUSTED" ? "rate_limit_error" : status === "UNAVAILABLE" || status === "INTERNAL" || status === "DEADLINE_EXCEEDED" ? "overloaded_error" : "api_error";
    this.failure = { type, message };
    return [...this.start(), ...this.closeBlock(), { event: "error", data: { type: "error", error: { type, message } } }];
  }

  message(): Record<string, unknown> {
    const content = this.content.map((block) => {
      if (block.type !== "tool_use") return block;
      let input: unknown = {};
      try { input = block.args ? JSON.parse(block.args) : {}; } catch { /* malformed vendor arguments become an empty tool input */ }
      return { type: "tool_use", id: block.id, name: block.name, input };
    });
    return { id: this.messageId, type: "message", role: "assistant", model: this.model, content, stop_reason: this.stopReason, stop_sequence: null, usage: this.usage };
  }
}

export function formatSse(event: AnthropicEvent): string {
  return `event: ${event.event}\ndata: ${JSON.stringify(event.data)}\n\n`;
}
